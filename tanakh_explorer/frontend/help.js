// ----------------------------------------------------------------- machinery
const helpPop = document.createElement("div");
helpPop.className = "help-pop";
helpPop.setAttribute("role", "dialog");
helpPop.hidden = true;
document.addEventListener("DOMContentLoaded", () => document.body.append(helpPop));

function helpFor(text, pageId) {
  const t = (text || "").replace(/\s+/g, " ").trim();
  return HELP[`${pageId}:${t}`] || HELP[t] || null;
}

function optionsHelp(control) {
  if (!control || control.tagName !== "SELECT") return [];
  return [...control.options].map((o) => [o.textContent, OPT[o.textContent]]).filter(([, v]) => v);
}

function openHelp(icon) {
  const title = icon.dataset.title;
  const body = icon.dataset.help;
  const control = icon._control;
  helpPop.innerHTML = "";
  const h = document.createElement("div");
  h.className = "help-title";
  h.textContent = title;
  const p = document.createElement("div");
  p.textContent = body;
  helpPop.append(h, p);
  const opts = optionsHelp(control);
  if (opts.length) {
    const ul = document.createElement("ul");
    for (const [k, v] of opts) {
      const li = document.createElement("li");
      const b = document.createElement("b");
      b.textContent = k + ": ";
      li.append(b, v);
      ul.append(li);
    }
    helpPop.append(ul);
  }
  helpPop.hidden = false;
  const r = icon.getBoundingClientRect();
  const w = Math.min(340, window.innerWidth - 24);
  helpPop.style.width = w + "px";
  let left = r.right + window.scrollX - w;
  left = Math.max(12 + window.scrollX, Math.min(left, window.scrollX + window.innerWidth - w - 12));
  helpPop.style.left = left + "px";
  helpPop.style.top = r.bottom + window.scrollY + 6 + "px";
  helpPop._owner = icon;
}

function closeHelp() { helpPop.hidden = true; helpPop._owner = null; }

document.addEventListener("click", (e) => {
  const icon = e.target.closest && e.target.closest(".hi");
  if (icon) {
    e.preventDefault();
    e.stopPropagation();
    if (helpPop._owner === icon && !helpPop.hidden) closeHelp(); else openHelp(icon);
    return;
  }
  if (!helpPop.contains(e.target)) closeHelp();
}, true);
document.addEventListener("keydown", (e) => {
  if (e.key === "Escape") closeHelp();
  if ((e.key === "Enter" || e.key === " ") && e.target.classList && e.target.classList.contains("hi")) {
    e.preventDefault();
    openHelp(e.target);
  }
});
window.addEventListener("resize", closeHelp);

function makeIcon(title, text, control) {
  const s = document.createElement("span");
  s.className = "hi";
  s.textContent = "ⓘ";
  s.tabIndex = 0;
  s.setAttribute("role", "button");
  s.setAttribute("aria-label", "הסבר: " + title);
  s.title = text;
  s.dataset.title = title;
  s.dataset.help = text;
  s._control = control;
  return s;
}

function ownText(el) {
  return [...el.childNodes].filter((n) => n.nodeType === 3).map((n) => n.textContent).join("").trim();
}

function attachHelp(root, pageId) {
  // field labels: <label class="field"><span>label</span><control></label>
  root.querySelectorAll(".field > span:first-child:not([data-h])").forEach((sp) => {
    sp.dataset.h = "1";
    const text = sp.textContent.trim();
    const control = sp.parentElement.querySelector("select, input, textarea");
    const help = helpFor(text, pageId);
    const opts = optionsHelp(control);
    if (help || opts.length) sp.append(" ", makeIcon(text, help || "", control));
  });
  // header globals: <label>text <select></label>
  root.querySelectorAll(".globals > label:not([data-h])").forEach((lb) => {
    lb.dataset.h = "1";
    const text = ownText(lb);
    const control = lb.querySelector("select");
    const help = helpFor(text, pageId);
    if (help) lb.insertBefore(makeIcon(text, help, control), control);
  });
  // checkboxes
  root.querySelectorAll("label.check:not([data-h])").forEach((lb) => {
    lb.dataset.h = "1";
    const text = ownText(lb);
    const help = helpFor(text, pageId);
    if (help) lb.append(makeIcon(text, help));
  });
  // buttons and links styled as buttons: tooltip on hover, ⓘ to tap
  root.querySelectorAll(".btn:not([data-h])").forEach((b) => {
    b.dataset.h = "1";
    const text = b.textContent.trim();
    const help = helpFor(text, pageId);
    if (!help) return;
    b.title = help;
    if (!b.classList.contains("small") || b.closest(".actions")) b.after(makeIcon(text, help));
  });
  // card titles and table headers
  root.querySelectorAll(".card > h3:not([data-h]), th:not([data-h])").forEach((el) => {
    el.dataset.h = "1";
    const text = el.textContent.trim();
    const help = helpFor(text, pageId);
    if (help) { el.title = help; el.append(" ", makeIcon(text, help)); }
  });
  // option tooltips (desktop hover)
  root.querySelectorAll("select:not([data-h])").forEach((s) => {
    s.dataset.h = "1";
    for (const o of s.options) if (OPT[o.textContent]) o.title = OPT[o.textContent];
  });
}

function watchHelp(getPageId) {
  let pending = false;
  const run = () => { pending = false; attachHelp(document.body, getPageId()); };
  new MutationObserver(() => { if (!pending) { pending = true; requestAnimationFrame(run); } })
    .observe(document.body, { childList: true, subtree: true });
  run();
}
